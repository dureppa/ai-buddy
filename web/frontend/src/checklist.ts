export function tasksFor(profileId: ProfileId): Task[] {
  const role = roleByProfile[primaryProfile(profileId)];
  const copyById = new Map(items.map((item) => [item.id, item]));
  return roleChecklist.tasks.map(({ id }) => {
    const item = copyById.get(id)!;
    return {
      id: item.id,
      stage: item.stage,
      icon: item.icon,
      tone: item.tone,
      owner: item.owner,
      due: dueByStage[item.stage],
      ...item.copy[role],
    };
  });
}

export function homeTasks(profileId: ProfileId): Task[] {
  const list = tasksFor(profileId);
  const stageId = profiles[profileId].stageId;
  if (stageId === 'first') return list.filter((task) => task.stage === 'week-1').slice(0, 4);
  if (stageId === 'midpoint') return list.filter((task) => task.id === 'equator-prep' || task.id === 'equator-meeting');
  return list.filter((task) => task.id === 'graduation' || task.id === 'internship-survey');
}

export function homeSectionTitle(profileId: ProfileId): string {
  return profiles[profileId].stageId === 'final' ? 'Итоги адаптации' : 'Ближайшие задачи';
}
